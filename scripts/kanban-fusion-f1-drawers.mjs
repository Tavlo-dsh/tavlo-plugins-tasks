import assert from 'node:assert/strict'

export async function verifyDrawers({ page, check, checkFocused, screenshot }) {
  const drawer = page.locator('.dsh-tasks-drawer')
  const title = drawer.locator('input[name="title"]')
  const brief = drawer.locator('textarea[name="brief"]')
  const editDescription = pane => pane.getByRole('button', { name: /^(编辑描述|Edit description)$/ })
  const create = page.locator('.dsh-tasks-toolbar .dsh-tasks-primary')
  const doing = page.locator('.dsh-tasks-col[data-stage="doing"]')
  const add = doing.locator('.dsh-tasks-colfoot button').last()
  const card = doing.locator('.dsh-tasks-card-title').first()
  const theme = page.locator('.dsh-tasks-appearance select')
  const settings = page.locator('.dsh-tasks-settings > summary')
  const manager = page.locator('dialog.dsh-tasks-column-manager[open]')
  const openSettings = async () => { if (await settings.evaluate(element => !element.parentElement.open)) await settings.click() }
  const close = async () => { await page.keyboard.press('Escape'); await drawer.waitFor({ state: 'hidden' }) }
  async function checkWidth(expected) {
    await page.waitForFunction(expected => {
      const bounds = document.querySelector('.dsh-tasks-drawer')?.getBoundingClientRect()
      return bounds && Math.abs(bounds.right - innerWidth) < 1 && Math.abs(bounds.width - expected) < 1
    }, expected)
  }
  await create.click()
  await checkFocused(title)
  await checkWidth(640)
  await title.fill('F1 draft')
  const handle = drawer.getByRole('separator')
  const edge = await handle.boundingBox()
  await page.mouse.move(edge.x + 4, edge.y + 70)
  await page.mouse.down()
  await page.mouse.move(edge.x - 36, edge.y + 70, { steps: 8 })
  await page.mouse.up()
  await checkWidth(680)
  await handle.focus()
  await page.keyboard.press('ArrowRight')
  await checkWidth(660)
  await close()
  await checkFocused(create)
  await create.click()
  assert.equal(await title.inputValue(), 'F1 draft')
  await checkWidth(660)
  await title.fill('')
  await close()
  await add.click()
  assert.equal(await drawer.locator('input[name="stage"]').inputValue(), 'doing')
  await title.fill('F1 task')
  await brief.fill('Initial brief')
  await screenshot(page, 'tavlo-create-drawer.png')
  await drawer.locator('[type="submit"]').click()
  await drawer.waitFor({ state: 'hidden' })
  await checkFocused(add)
  await card.waitFor()
  check('Global and column create drawers preserve draft, chosen column, width and invoking focus')

  await doing.locator('.dsh-tasks-card-brief').first().click()
  await checkFocused(title)
  await title.fill('F1 edited')
  await page.keyboard.press('Escape')
  const discard = page.getByRole('alertdialog')
  await discard.waitFor()
  await discard.getByRole('button', { name: /继续编辑|Keep editing/i }).click()
  await discard.waitFor({ state: 'hidden' })
  assert.equal(await title.inputValue(), 'F1 edited')
  await editDescription(drawer).click()
  await brief.fill('Saved description')
  await drawer.locator('.dsh-tasks-form-actions .dsh-tasks-primary').click()
  await page.waitForFunction(() => document.querySelector('.dsh-tasks-card-title')?.textContent === 'F1 edited')
  await drawer.getByRole('button', { name: /^(启动任务|Start task)$/ }).waitFor()
  await close()
  await checkFocused(card)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByText(/^(任务|Tasks)$/).first().click()
  await card.click()
  await drawer.locator('.dsh-tasks-description-markdown').getByText('Saved description', { exact: true }).waitFor()
  await editDescription(drawer).click()
  await brief.fill('Unsaved local note')
  const second = await page.context().newPage()
  try {
    await second.goto(page.url(), { waitUntil: 'domcontentloaded' })
    await second.getByText(/^(任务|Tasks)$/).first().click()
    await second.locator('.dsh-tasks-card-title').first().click()
    const other = second.locator('.dsh-tasks-drawer')
    await editDescription(other).click()
    await other.locator('[name=brief]').fill('Second tab edit')
    await other.locator('.dsh-tasks-primary').click()
    await drawer.locator('[role="alert"]').waitFor()
    assert.equal(await brief.inputValue(), 'Unsaved local note')
    assert(await drawer.locator('.dsh-tasks-primary').isDisabled())
    await drawer.locator('[role="alert"] button').click()
    await page.getByRole('alertdialog').getByRole('button', { name: /放弃.*载入|discard.*load/i }).click()
    await drawer.locator('.dsh-tasks-description-markdown').getByText('Second tab edit', { exact: true }).waitFor()
  } finally { await second.close() }
  check('Live changes from a second page preserve the dirty draft and block stale saves until explicit reload')
  await drawer.getByRole('button', { name: /^(启动任务|Start task)$/ }).click()
  await page.locator('dialog[open]').waitFor()
  await page.keyboard.press('Escape')
  await page.locator('dialog[open]').waitFor({ state: 'hidden' })
  check('Card body opens editable details; dirty Escape keeps draft, save survives reload, launch still asks for confirmation')

  for (const appearance of ['ios', 'paper']) {
    await openSettings()
    await theme.selectOption(appearance)
    await page.locator(`body[data-dsh-task-appearance="${appearance}"]`).waitFor()
    await openSettings()
    await page.getByRole('button', { name: /^(管理列|Manage columns)$/ }).click()
    const addColumn = manager.getByRole('button', { name: /^(添加列|Add column)$/ })
    await addColumn.waitFor()
    assert.equal(await page.locator('.dsh-tasks-board').getByRole('button', { name: /添加列|Add column/ }).count(), 0)
    await screenshot(page, `tavlo-columns-${appearance}.png`)
    await page.keyboard.press('Escape')
    await manager.waitFor({ state: 'hidden' })
    await checkFocused(settings)
    await card.click()
    await checkWidth(660)
    await screenshot(page, `tavlo-detail-${appearance}.png`)
    await close()
    await checkFocused(card)
  }
  await openSettings()
  await theme.selectOption('inherit')
  await page.setViewportSize({ width: 390, height: 740 })
  await card.click()
  await checkWidth(390)
  assert(await handle.isHidden())
  const firstAction = drawer.getByRole('button', { name: /^(复制任务 ID|Copy task ID)$/ })
  await firstAction.focus()
  await page.keyboard.press('Shift+Tab')
  await checkFocused(drawer.getByRole('button', { name: /^(启动任务|Start task)$/ }))
  await page.keyboard.press('Tab')
  await checkFocused(firstAction)
  const footer = await drawer.locator('.dsh-tasks-form-actions').boundingBox()
  assert(footer && footer.y + footer.height <= 741)
  await screenshot(page, 'tavlo-detail-narrow.png')
  await close()
  await checkFocused(card)
  await page.setViewportSize({ width: 1680, height: 960 })
  check('Host, iOS and paper drawers work; narrow drawer fills the viewport with reachable actions')

  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await card.click()
  const taskId = await card.locator('xpath=ancestor::article').getAttribute('data-task-id')
  assert(taskId)
  await firstAction.click()
  await drawer.getByRole('status').filter({ hasText: /^(已复制任务 ID|Task ID copied)$/ }).waitFor()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), taskId)
  const deleteTask = drawer.getByRole('button', { name: /^(删除任务|Delete task)$/ })
  assert(await deleteTask.isHidden())
  await drawer.locator('.dsh-tasks-detail-menu summary').click()
  await deleteTask.click()
  const confirmation = page.locator('dialog[open]')
  await confirmation.getByRole('button', { name: /^(取消|Cancel)$/ }).click()
  await confirmation.waitFor({ state: 'hidden' })
  assert(await card.isVisible())
  check('Task ID can be copied, and deleting from the details menu still requires confirmation')
}
