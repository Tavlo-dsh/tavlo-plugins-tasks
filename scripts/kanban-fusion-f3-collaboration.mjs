import assert from 'node:assert/strict'

export async function verifyCollaboration({ page, check, screenshot }) {
  const drawer = page.locator('.dsh-tasks-drawer'), title = 'F3 Acceptance', phrase = 'handover-evidence'
  const activityTab = drawer.getByRole('tab', { name: /^(动态|Activity)$/ })
  const detailsTab = drawer.getByRole('tab', { name: /^(详情|Details)$/ })
  const timeline = drawer.getByRole('tabpanel', { name: /^(动态|Activity)$/ })
  const commentInput = drawer.locator('[name=comment]')
  const submitComment = drawer.getByRole('button', { name: /^(发布评论|Post comment)$/ })
  const checkImageOrder = async () => {
    assert(await drawer.locator('.dsh-tasks-properties').evaluate(properties => {
      const images = properties.closest('.dsh-tasks-dialog-body').querySelector('.dsh-tasks-images')
      return images && Boolean(properties.compareDocumentPosition(images) & Node.DOCUMENT_POSITION_FOLLOWING)
    }), 'Expected task images after the label and other properties')
  }
  const choose = async (container, name, label) => {
    const field = container.locator('.dsh-tasks-select').filter({ has: page.locator(`input[name="${name}"]`) })
    await field.getByRole('combobox').click()
    await field.getByRole('option', { name: label, exact: true }).click()
  }
  await page.getByRole('button', { name: /^(新建任务|New task)$/ }).click()
  await drawer.locator('[name=title]').fill(title)
  await checkImageOrder()
  await drawer.locator('[name=brief]').fill('**Acceptance**\n\n<img src=x onerror="window.f3unsafe=true">')
  for (const [name, text] of [['labelId', 'Review'], ['priority', 'Expedite']]) {
    const field = drawer.locator('.dsh-tasks-select').filter({ has: page.locator(`input[name="${name}"]`) })
    await field.getByRole('combobox').fill(text)
    await field.getByRole('option', { name: new RegExp(text) }).click()
    await drawer.locator(`input[name="${name}"]:not([value=""])`).waitFor({ state: 'attached' })
  }
  const dateTrigger = drawer.getByRole('button', { name: /^(截止日期|Due date):/ }), calendar = drawer.locator('.dsh-tasks-date-popup')
  await dateTrigger.click()
  await calendar.getByRole('button', { name: /^(明天|Tomorrow)$/ }).click()
  assert(await drawer.locator('[name=dueDate]').inputValue())
  await drawer.getByRole('button', { name: /^(清除日期|Clear date)$/ }).click()
  assert.equal(await drawer.locator('[name=dueDate]').inputValue(), '')
  await dateTrigger.click()
  assert.equal(await calendar.locator('select:visible').count(), 0)
  await calendar.locator('.rdp-button_previous').click()
  const viewport = page.viewportSize()
  await page.setViewportSize({ width: 360, height: 740 })
  await calendar.scrollIntoViewIfNeeded()
  assert(await calendar.evaluate(node => node.scrollWidth <= node.clientWidth + 1))
  await screenshot(calendar, 'tavlo-due-date-narrow.png')
  await page.setViewportSize(viewport)
  const day = calendar.locator('td:not(.rdp-outside) [data-slot=calendar-day]').first(), expectedDate = await day.getAttribute('data-day')
  await day.click()
  assert.equal(await drawer.locator('[name=dueDate]').inputValue(), expectedDate)
  await dateTrigger.click(); await page.keyboard.press('Escape'); await dateTrigger.waitFor()
  await drawer.locator('[type=submit]').click()
  const card = page.getByRole('button', { name: title, exact: true })
  await card.click()
  assert.equal(await drawer.locator('[name=dueDate]').inputValue(), expectedDate)
  await dateTrigger.click(); await calendar.locator('[data-selected-single=true]').waitFor(); await page.keyboard.press('Escape')
  await checkImageOrder()
  await drawer.locator('.dsh-tasks-description-markdown strong', { hasText: 'Acceptance' }).waitFor()
  assert.equal(await drawer.locator('[onerror]').count(), 0)
  await drawer.getByRole('button', { name: /^(编辑描述|Edit description)$/ }).click()
  const brief = drawer.locator('[name=brief]'), savedBrief = await brief.inputValue()
  await brief.fill('Unsaved description')
  await detailsTab.focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await activityTab.getAttribute('aria-selected'), 'true')
  await commentInput.fill(phrase)
  await detailsTab.click()
  assert.equal(await brief.inputValue(), 'Unsaved description')
  await brief.fill(savedBrief)
  await activityTab.click()
  assert.equal(await commentInput.inputValue(), phrase)
  await submitComment.click()
  await timeline.locator('li', { hasText: phrase }).waitFor()
  await screenshot(page, 'tavlo-f3-detail.png')
  check('Tavlo drawer creates a label and custom priority inline, picks a due date, previews Markdown and records a comment')
  await page.keyboard.press('Escape')
  await page.getByRole('searchbox').fill(phrase)
  await page.locator('.dsh-tasks-card-brief', { hasText: phrase }).waitFor()
  await page.locator('.dsh-tasks-filter summary').click()
  const filters = page.locator('.dsh-tasks-filter')
  await choose(filters, 'labelId', 'Review')
  await choose(filters, 'dueDate', /^(已逾期|Overdue)$/)
  await choose(filters, 'priority', 'P0')
  await card.waitFor({ state: 'hidden' })
  await choose(filters, 'priority', 'Expedite')
  await card.waitFor()
  assert.equal(await page.locator('.dsh-tasks-grip').count(), 0)
  const reset = filters.getByRole('button', { name: /清除筛选|Clear filters/i })
  await reset.click()
  assert(await reset.isDisabled())
  assert.equal(await page.getByRole('searchbox').inputValue(), phrase)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByText(/^(任务|Tasks)$/).first().click()
  await card.click()
  assert.equal(await drawer.locator('[name=priority]').inputValue(), 'Expedite')
  await activityTab.click()
  await timeline.locator('li', { hasText: phrase }).waitFor()
  check('Tavlo comment-only result shows an excerpt, combines three filters, disables reordering and survives reload')

  for (let index = 1; index <= 25; index++) {
    const text = index === 25 ? 'LongComment'.repeat(45) : `Timeline comment ${index}`
    await commentInput.fill(text)
    await submitComment.click()
    await timeline.getByText(text, { exact: true }).waitFor()
  }
  await page.keyboard.press('Escape')
  await drawer.waitFor({ state: 'hidden' })
  await card.click()
  await activityTab.click()
  await timeline.getByRole('button', { name: /^(更早的动态|Older activity)$/ }).click()
  const firstEvent = timeline.locator('li[data-kind=created]')
  await firstEvent.waitFor()
  const pinned = timeline.getByText('Timeline comment 5', { exact: true })
  await pinned.evaluate(element => element.scrollIntoView({ block: 'center' }))
  const previousTop = (await pinned.boundingBox()).y
  const second = await page.context().newPage()
  try {
    await second.goto(page.url(), { waitUntil: 'domcontentloaded' })
    await second.getByText(/^(任务|Tasks)$/).first().click()
    await second.getByRole('button', { name: title, exact: true }).click()
    await second.getByRole('tab', { name: /^(动态|Activity)$/ }).click()
    await second.locator('.dsh-tasks-drawer [name=comment]').fill('Live update from second tab')
    await second.getByRole('button', { name: /^(发布评论|Post comment)$/ }).click()
    await page.waitForFunction(() => document.querySelector('.dsh-tasks-activity li')?.textContent.includes('Live update from second tab'))
    assert(await firstEvent.isVisible())
    assert(Math.abs((await pinned.boundingBox()).y - previousTop) < 3, 'Expected live updates to retain the reading position')
  } finally { await second.close() }
  assert.equal(await timeline.locator('li time[datetime]').count(), 28)
  check('Live timeline prepends updates without dropping older pages or moving the reading position')

  await page.keyboard.press('Escape')
  const taskMenu = page.locator('.dsh-tasks-card', { has: card }).locator('.dsh-tasks-card-actions summary')
  await card.hover()
  await taskMenu.click()
  await page.getByRole('button', { name: /^(移入 进行中|Move to In progress)$/i }).click()
  await page.locator('.dsh-tasks-col[data-stage=doing]').getByRole('button', { name: title, exact: true }).waitFor()

  const theme = page.locator('.dsh-tasks-appearance select')
  if (await theme.count()) {
    for (const appearance of ['inherit', 'ios', 'paper']) {
      for (const colorScheme of ['light', 'dark']) {
        await page.emulateMedia({ colorScheme })
        await page.locator(colorScheme === 'dark' ? 'body[data-ds-dark-theme]' : 'body:not([data-ds-dark-theme])').waitFor()
        for (const width of [1680, 390]) {
          await page.setViewportSize({ width, height: width === 390 ? 740 : 960 })
          await theme.selectOption(appearance)
          await page.locator(appearance === 'inherit' ? 'body:not([data-dsh-task-appearance])' : `body[data-dsh-task-appearance=${appearance}]`).waitFor()
          await card.click()
          await activityTab.click()
          await timeline.getByText(/^(待开始 → 进行中|To do → In progress)$/i).waitFor()
          assert(await timeline.evaluate(element => element.scrollWidth <= element.clientWidth + 1))
          if (width === 390) assert.equal(await drawer.evaluate(element => getComputedStyle(element).borderRadius), '0px')
          await screenshot(page, `task-timeline-${appearance}-${colorScheme}-${width}.png`)
          await page.keyboard.press('Escape')
          await drawer.waitFor({ state: 'hidden' })
        }
      }
    }
    await page.setViewportSize({ width: 1680, height: 960 })
    await page.emulateMedia({ colorScheme: 'light' })
    await theme.selectOption('inherit')
    check('Task activity renders in all three appearances, light and dark, at desktop and narrow widths')
  }
}
