import assert from 'node:assert/strict'

export async function verifyColumns({ page, check, screenshot }) {
  const column = name => page.locator('.dsh-tasks-col').filter({ has: page.locator('.dsh-tasks-colname', { hasText: name }) })
  const task = name => page.locator('.dsh-tasks-card').filter({ has: page.getByRole('button', { name, exact: true }) })
  const settings = page.locator('.dsh-tasks-settings > summary')
  const manage = async () => {
    await settings.click()
    await page.getByRole('button', { name: /^(管理列|Manage columns)$/ }).click()
  }
  const manager = page.locator('dialog.dsh-tasks-column-manager[open]')
  const drawer = page.locator('.dsh-tasks-drawer')
  const overview = page.locator('.dsh-tasks-insights')
  const viewport = page.viewportSize()
  await page.locator('.dsh-tasks-col').first().waitFor()
  assert(await overview.isHidden())
  await page.evaluate(() => { document.documentElement.dataset.fullscreen = 'true' })
  await overview.waitFor()
  const rail = await overview.boundingBox(), firstColumn = await page.locator('.dsh-tasks-col').first().boundingBox()
  assert(rail.x + rail.width <= firstColumn.x && firstColumn.width >= 270 && firstColumn.width <= 442)
  await page.setViewportSize({ ...viewport, width: 1150 })
  await overview.waitFor({ state: 'hidden' })
  await page.setViewportSize(viewport)
  await overview.waitFor()
  await page.evaluate(() => { delete document.documentElement.dataset.fullscreen })
  await overview.waitFor({ state: 'hidden' })
  check('Insights only occupy space on a wide fullscreen board and leave readable column widths')
  await manage()
  const add = manager.locator('.dsh-tasks-manage-create')
  await add.locator('input[name=name]').fill('F2 Review')
  await add.locator('[type="submit"]').click()
  await manager.locator('.dsh-tasks-manage-list input[value="F2 Review"]').waitFor()
  await page.keyboard.press('Escape')
  await manager.waitFor({ state: 'hidden' })
  assert(await settings.evaluate(element => document.activeElement === element))
  const review = column('F2 Review')
  const doing = page.locator('.dsh-tasks-col[data-column-id="stage:doing"]')
  for (const title of ['F2 A', 'F2 B']) {
    await review.locator('.dsh-tasks-colfoot button').last().click()
    await drawer.locator('input[name="title"]').fill(title)
    await drawer.getByRole('button', { name: /^(创建任务|Create task)$/ }).click()
    await review.getByRole('button', { name: title, exact: true }).waitFor()
  }
  check('Custom column creation and column-scoped task creation use the selected stable ID')
  async function drag(name, destination, fraction, cancel = false) {
    const handle = task(name).locator(cancel ? '.dsh-tasks-card-title' : '.dsh-tasks-card-state')
    const source = await handle.boundingBox(), target = await destination.boundingBox()
    assert(source && target)
    await page.mouse.move(source.x + 6, source.y + 6)
    await page.mouse.down()
    await page.mouse.move(source.x + 18, source.y + 6)
    await page.locator('[data-dragging="true"]').waitFor()
    await page.mouse.move(target.x + target.width / 2, target.y + target.height * fraction, { steps: 12 })
    if (cancel) await page.keyboard.press('Escape')
    await page.mouse.up()
    await page.locator('[data-dragging="true"]').waitFor({ state: 'hidden' })
  }
  await drag('F2 A', task('F2 B'), .8)
  await page.waitForFunction(() => [...document.querySelectorAll('.dsh-tasks-card-title')].map(node => node.textContent).join() === 'F2 B,F2 A')
  await drag('F2 A', doing.locator('.dsh-tasks-empty'), .5, true)
  assert.equal(await doing.locator('.dsh-tasks-card').count(), 0)
  await drag('F2 A', doing.locator('.dsh-tasks-empty'), .5)
  await doing.getByRole('button', { name: 'F2 A', exact: true }).waitFor()
  assert(await drawer.isHidden())
  check('Real pointer reorders within a column, cancels without moving, and drops into an empty column')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByText(/^(任务|Tasks)$/).first().click()
  await review.getByRole('button', { name: 'F2 B', exact: true }).waitFor()
  await doing.getByRole('button', { name: 'F2 A', exact: true }).waitFor()
  const peer = await page.context().newPage()
  try {
    await peer.goto(page.url(), { waitUntil: 'domcontentloaded' })
    await peer.getByText(/^(任务|Tasks)$/).first().click()
    await peer.locator('.dsh-tasks-col[aria-label="F2 Review"]').waitFor()
    await manage()
    const form = manager.locator('.dsh-tasks-manage-list form').filter({ has: page.locator('input[value="F2 Review"]') })
    assert(await form.getByRole('button', { name: /删除空列|Delete empty column/ }).isDisabled())
    await form.locator('input').fill('F2 Verify')
    await form.locator('[type="submit"]').click()
    await peer.locator('.dsh-tasks-col[aria-label="F2 Verify"] .dsh-tasks-card').waitFor()
    const source = await manager.locator('form').filter({ has: page.locator('input[value="F2 Verify"]') }).locator('.dsh-tasks-grip').boundingBox()
    const target = await manager.locator('form[data-column-id="stage:todo"]').boundingBox()
    await page.mouse.move(source.x + 5, source.y + 5)
    await page.mouse.down()
    await page.mouse.move(source.x + 15, source.y + 5)
    await page.mouse.move(target.x + 40, target.y + 3, { steps: 12 })
    await page.mouse.up()
    await peer.waitForFunction(() => document.querySelector('.dsh-tasks-col')?.getAttribute('aria-label') === 'F2 Verify')
    await page.keyboard.press('Escape')
  } finally { await peer.close() }
  const search = page.getByRole('searchbox')
  await search.fill('F2 A')
  assert.equal(await page.locator('.dsh-tasks-grip').count(), 0)
  const menu = task('F2 A').locator('summary')
  await menu.focus()
  await page.keyboard.press('Enter')
  await task('F2 A').getByRole('button', { name: /^(移入|Move to) F2 Verify$/ }).focus()
  await page.keyboard.press('Enter')
  const verify = column('F2 Verify')
  await verify.getByRole('button', { name: 'F2 A', exact: true }).waitFor()
  await search.fill('')
  await menu.focus()
  await page.keyboard.press('Enter')
  await task('F2 A').getByRole('button', { name: /^(向前移动|Move earlier)$/ }).focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('.dsh-tasks-col[aria-label="F2 Verify"] .dsh-tasks-card-title')?.textContent === 'F2 A')
  check('Filtered views disable manual sorting; keyboard menus can move across columns and reorder in the full view')
  await page.evaluate(() => document.documentElement.requestFullscreen())
  await overview.waitFor()
  await screenshot(page, 'tavlo-f2-board.png')
  const theme = page.locator('.dsh-tasks-appearance select')
  if (await theme.count()) {
    await settings.click()
    await theme.selectOption('paper')
    await page.keyboard.press('Escape')
    await page.locator('body[data-dsh-task-appearance="paper"]').waitFor()
    assert((await page.locator('.dsh-tasks-col').first().boundingBox()).width <= 442)
    await screenshot(page, 'tavlo-insights-paper.png')
  }
  await page.evaluate(() => document.exitFullscreen())
  await overview.waitFor({ state: 'hidden' })
  check('Refresh restores card placement; a second tab receives column rename and drag reorder without losing cards')
}
